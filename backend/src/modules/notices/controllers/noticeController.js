const mongoose = require('mongoose');
const Notice = require('../models/Notice');
const asyncHandler = require('../../../shared/middleware/asyncHandler');

// @desc    Get all notices
// @route   GET /api/notices
exports.getNotices = asyncHandler(async (req, res) => {
  const notices = await Notice.find({}).sort({ pinned: -1, createdAt: -1 });
  res.json({ success: true, count: notices.length, data: notices });
});

// @desc    Create a notice
// @route   POST /api/notices
exports.createNotice = asyncHandler(async (req, res) => {
  const count = await Notice.countDocuments();
  const noticeCode = req.body.noticeCode || `NOT-${100 + count + 1}`;
  
  const noticeData = { ...req.body };
  // Clean up non-ObjectId _id generated by client so MongoDB creates a proper ObjectId
  if (noticeData._id && !mongoose.Types.ObjectId.isValid(noticeData._id)) {
    delete noticeData._id;
  }

  const textContent = noticeData.content || noticeData.description || noticeData.fullContent || noticeData.shortDescription || '';
  noticeData.content = textContent;
  noticeData.description = textContent;
  noticeData.fullContent = textContent;
  noticeData.shortDescription = noticeData.shortDescription || textContent.slice(0, 150);
  noticeData.targetAudience = noticeData.targetAudience || noticeData.to || 'All Employees';
  noticeData.to = noticeData.to || noticeData.targetAudience || 'All Employees';
  noticeData.postedBy = noticeData.postedBy || noticeData.createdBy || req.user?.name || 'HR Operations';
  noticeData.createdBy = noticeData.createdBy || noticeData.postedBy || req.user?.name || 'HR Operations';
  noticeData.isImportant = noticeData.priority === 'urgent' || noticeData.priority === 'high' || !!noticeData.isImportant;
  noticeData.noticeCode = noticeCode;

  const notice = await Notice.create(noticeData);
  res.status(201).json({ success: true, data: notice });
});

// @desc    Update a notice
// @route   PUT /api/notices/:id
exports.updateNotice = asyncHandler(async (req, res) => {
  const { id } = req.params;
  const updateData = { ...req.body };
  if (updateData._id) delete updateData._id;

  let notice = null;
  if (mongoose.Types.ObjectId.isValid(id)) {
    notice = await Notice.findByIdAndUpdate(id, updateData, { new: true, runValidators: false });
  } else {
    notice = await Notice.findOneAndUpdate({ noticeCode: id }, updateData, { new: true, runValidators: false });
  }

  if (!notice) {
    return res.status(404).json({ success: false, message: 'Notice not found' });
  }
  res.json({ success: true, data: notice });
});

// @desc    Delete a notice
// @route   DELETE /api/notices/:id
exports.deleteNotice = asyncHandler(async (req, res) => {
  const { id } = req.params;
  let notice = null;
  if (mongoose.Types.ObjectId.isValid(id)) {
    notice = await Notice.findByIdAndDelete(id);
  } else {
    notice = await Notice.findOneAndDelete({ noticeCode: id });
  }

  if (!notice) {
    return res.status(404).json({ success: false, message: 'Notice not found' });
  }
  res.json({ success: true, message: 'Notice removed', data: {} });
});

