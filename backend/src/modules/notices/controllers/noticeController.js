const mongoose = require('mongoose');
const Notice = require('../models/Notice');
const asyncHandler = require('../../../shared/middleware/asyncHandler');
const { emitToAll } = require('../../../shared/socket/socketManager');

// @desc    Get all notices
// @route   GET /api/notices
exports.getNotices = asyncHandler(async (req, res) => {
  const notices = await Notice.find({}).sort({ pinned: -1, createdAt: -1 });
  res.json({ success: true, count: notices.length, data: notices });
});

// @desc    Create a notice
// @route   POST /api/notices
exports.createNotice = asyncHandler(async (req, res) => {
  const u = req.user;
  if (u) {
    const isLeader = (u.role || '').toLowerCase().includes('lead') || (u.role || '').toLowerCase().includes('manager');
    const canPost = u.isAdmin || u.systemRole === 'admin' || u.systemRole === 'hr' || u.isDelegatedAdmin || isLeader || u.permissions?.notices || u.permissions?.postNotices || u.permissions?.allAccess;
    if (!canPost) {
      return res.status(403).json({ success: false, message: 'Access denied: You do not have permission to publish notices.' });
    }
  }

  const count = await Notice.countDocuments();
  const noticeCode = req.body.noticeCode || `NOT-${100 + count + 1}`;
  
  const noticeData = { ...req.body };
  // Clean up non-ObjectId _id generated by client so MongoDB creates a proper ObjectId
  if (noticeData._id && !mongoose.Types.ObjectId.isValid(noticeData._id)) {
    delete noticeData._id;
  }

  const textContent = noticeData.content || noticeData.description || noticeData.fullContent || noticeData.shortDescription || '';
  noticeData.content = textContent;
  noticeData.description = textContent;
  noticeData.fullContent = textContent;
  noticeData.shortDescription = noticeData.shortDescription || textContent.slice(0, 150);
  noticeData.targetAudience = noticeData.targetAudience || noticeData.to || 'All Employees';
  noticeData.to = noticeData.to || noticeData.targetAudience || 'All Employees';
  const u = req.user;
  const actorName = u ? (u.name || u.email || 'HR Operations') : 'HR Operations';
  const actorLabel = u?.employeeCode ? `${actorName} (${u.employeeCode})` : actorName;
  const actorId = u?._id ? String(u._id) : (u?.id || '');
  const actorCode = u?.employeeCode || '';

  noticeData.postedBy = noticeData.postedBy || actorLabel;
  noticeData.postedById = noticeData.postedById || actorId;
  noticeData.postedByCode = noticeData.postedByCode || actorCode;
  noticeData.createdBy = noticeData.createdBy || actorLabel;
  noticeData.createdById = noticeData.createdById || actorId;
  noticeData.createdByCode = noticeData.createdByCode || actorCode;
  noticeData.authorName = noticeData.authorName || actorLabel;
  noticeData.author = noticeData.author || actorLabel;
  noticeData.isImportant = noticeData.priority === 'urgent' || noticeData.priority === 'high' || !!noticeData.isImportant;
  noticeData.noticeCode = noticeCode;

  const notice = await Notice.create(noticeData);
  emitToAll('notice:updated', { action: 'create', item: notice });
  res.status(201).json({ success: true, data: notice });
});

// @desc    Update a notice
// @route   PUT /api/notices/:id
exports.updateNotice = asyncHandler(async (req, res) => {
  const { id } = req.params;
  const updateData = { ...req.body };
  if (updateData._id) delete updateData._id;

  const existing = mongoose.Types.ObjectId.isValid(id)
    ? await Notice.findById(id)
    : await Notice.findOne({ noticeCode: id });

  if (!existing) {
    return res.status(404).json({ success: false, message: 'Notice not found' });
  }

  const u = req.user;
  if (u) {
    const isLeader = (u.role || '').toLowerCase().includes('lead') || (u.role || '').toLowerCase().includes('manager');
    const isPrivileged = Boolean(u.isAdmin || u.isDelegatedAdmin || u.systemRole === 'admin' || u.systemRole === 'hr' || isLeader || u.permissions?.postNotices || u.permissions?.allAccess);
    const isCreator = Boolean(u.name && (existing.createdBy === u.name || existing.postedBy === u.name));
    if (!isPrivileged && !isCreator) {
      return res.status(403).json({ success: false, message: 'Access denied: You do not have permission to edit this notice.' });
    }

    const actorName = u.name || u.email || 'Admin';
    const actorLabel = u.employeeCode ? `${actorName} (${u.employeeCode})` : actorName;
    updateData.lastUpdatedBy = updateData.lastUpdatedBy || actorLabel;
    updateData.lastUpdatedById = updateData.lastUpdatedById || String(u._id || u.id || '');
    updateData.lastUpdatedByCode = updateData.lastUpdatedByCode || u.employeeCode || '';
    updateData.lastUpdatedAt = new Date();
  }

  Object.assign(existing, updateData);
  await existing.save();
  emitToAll('notice:updated', { action: 'update', item: existing });
  res.json({ success: true, data: existing });
});

// @desc    Delete a notice
// @route   DELETE /api/notices/:id
exports.deleteNotice = asyncHandler(async (req, res) => {
  const { id } = req.params;
  let notice = null;
  if (mongoose.Types.ObjectId.isValid(id)) {
    notice = await Notice.findById(id);
  } else {
    notice = await Notice.findOne({ noticeCode: id });
  }

  if (!notice) {
    return res.status(404).json({ success: false, message: 'Notice not found' });
  }

  const u = req.user;
  if (u) {
    const userRoleLower = (u.role || '').toLowerCase();
    const isAdminOrHR = u.isAdmin || u.systemRole === 'admin' || u.systemRole === 'hr' || userRoleLower === 'admin' || userRoleLower === 'administrator' || userRoleLower.includes('hr') || u.isDelegatedAdmin || u.permissions?.allAccess || u.permissions?.deleteNotices;
    const isCreator =
      String(notice.createdById) === String(u._id) ||
      String(notice.createdById) === String(u.id) ||
      String(notice.createdById) === String(u.employeeCode) ||
      (notice.postedBy && u.name && notice.postedBy.toLowerCase().trim() === u.name.toLowerCase().trim()) ||
      (notice.createdBy && u.name && notice.createdBy.toLowerCase().trim() === u.name.toLowerCase().trim());

    if (!isAdminOrHR && !isCreator) {
      return res.status(403).json({ success: false, message: 'Access denied: You do not have permission to delete this notice.' });
    }
  }

  await Notice.deleteOne({ _id: notice._id });
  emitToAll('notice:updated', { action: 'delete', id: String(notice._id), noticeCode: notice.noticeCode });
  res.json({ success: true, message: 'Notice removed', data: {} });
});

